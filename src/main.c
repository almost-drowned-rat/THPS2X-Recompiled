/**
 * THPS 2X - recompiled game entry point.
 *
 * Boot sequence after sp00nznet/xboxrecomp templates/new-game/src/main.c
 * (commit 193e299, MIT) and refs/defjam_recomp src/main.c; see docs/sources.md.
 * OS-specific parts (log, crash handler, paths) live in platform/.
 *
 * XBE (docs/xbe.md):
 *   Title:       Tony Hawk's Pro Skater 2X (USA), title ID 0x41560001
 *   XDK:         3947 (D3D8 3947, DSOUND 3925, rest 3911)
 *   Base addr:   0x00010000
 *   Entry point: 0x001B9FD3
 *   .text:       0x00068B40, 0x189110 bytes; 13 sections; 167 kernel imports
 *   SHA1:        469818E015AED2730641C0BDCBD2557D8A6B8BB4
 */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>

