/* launcher/main.c -- "THPS 2X Recomp.exe", the one file a player downloads
 * (docs/release_plan.md): the toolkit's launcher (src/launcher) with THPS 2X's names, versions and icon. The
 * release script (tools/release.ps1) appends the payload to the built exe.
 *
 * Since 2026-11-05 (maintainer: THPS 2X takes over the launcher rework of Panzer Dragoon Orta Recompiled, which has
 * the NG2 launcher's design): a fresh download started without arguments opens the setup window (setup_win32.c:
 * disc image, install folder, Go -> Play); it copies this exe into the install folder and runs the copy there with
 * --image / --no-start / --setup-parent. Every other start - an installed folder (data\build\stamp.txt), a game\
 * folder the player filled by hand, --repair, the setup's copy - goes to the toolkit's launcher as before, with the
 * progress in the same look. No Vulkan 1.3 device: an apology box before anything else (maintainer 2026-11-04;
 * THPS2X.exe asks the same). */

#include "launcher.h"
#include "port_icon.h"          /* g_port_icon_bmp: assets/icon_64.bmp, generated by CMake */
#include "setup_win32.h"

#include <SDL3/SDL.h>
#include <SDL3/SDL_main.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* 1 when the exe's folder is (being) used as a game folder already: then the toolkit's launcher takes over */
static int folder_in_use(void)
{
    const char *base = SDL_GetBasePath();
    char p[1024];
    SDL_PathInfo info;
    if (!base)
        return 1;
    snprintf(p, sizeof p, "%sdata/build/stamp.txt", base);
    if (SDL_GetPathInfo(p, &info))
        return 1;                       /* installed: start the game */
    snprintf(p, sizeof p, "%sgame/default.xbe", base);
    if (SDL_GetPathInfo(p, &info))
        return 1;                       /* extracted disc files put into game\ by hand */
    snprintf(p, sizeof p, "%sgame", base);
    if (SDL_GetPathInfo(p, &info) && info.type == SDL_PATHTYPE_DIRECTORY) {
        /* an .iso put into game\ by hand (the toolkit's way): any file other than README.txt counts */
        char **files = SDL_GlobDirectory(p, "*", 0, NULL);
        int used = 0, i;
        for (i = 0; files && files[i]; i++)
            if (SDL_strcasecmp(files[i], "README.txt") != 0)
                used = 1;
        SDL_free(files);
        if (used)
            return 1;
    }
    return 0;
}

int main(int argc, char **argv)
{
    /* the supported versions (CLAUDE.md "Supported versions"; src/main.c thps_game_setup) */
    static const xr_game_version versions[] = {
        { "USA", "469818E015AED2730641C0BDCBD2557D8A6B8BB4" },
    };
    XrLauncherConfig c = {
        "THPS 2X",
        "THPS 2X (USA)",
        "THPS 2X Recomp",
        "THPS2X.exe",
        0x41560001u,
        versions,
        sizeof versions / sizeof versions[0],
        g_port_icon_bmp,
        sizeof g_port_icon_bmp,
    };
    int i, parent = 0;

    for (i = 1; i + 1 < argc; i++)
        if (!strcmp(argv[i], "--setup-parent")) {
            thps_setup_set_parent(strtoull(argv[i + 1], NULL, 10));
            parent = 1;
        }
    if (argc <= 1 && !folder_in_use())
        return thps_setup_window();
    /* the toolkit's launcher; an installed folder only starts THPS2X.exe, which checks Vulkan itself */
    if (!parent && !folder_in_use() && !thps_vk_gate())
        return 1;
    return xr_launcher_main(&c, argc, argv);
}
